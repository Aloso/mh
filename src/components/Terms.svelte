	<summary>Geschäftsbedingungen</summary>

	<p>
		Die Anmeldung für den Musikunterricht bezieht sich auf das gesamte Schuljahr. Beendet der
		Schüler vor Ablauf des Unterrichtsjahres ohne Absprache den Unterricht, besteht weiterhin die
		Gebührenpflicht für das gesamte Schuljahr. Die Probezeit ist davon ausgenommen.
	</p>
	<p>
		Vom Schüler verursachte Unterrichtsausfälle begründen keinen Anspruch auf Rückgabe der
		Unterrichtsgebühren. Unterrichtsstunden, die durch Krankheit oder unvermeidliche Verhinderung
		des Lehrers ausfallen, sind bis jährlich zwei Stunden gebührenpflichtig.
	</p>
</details>

