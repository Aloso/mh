	<h2>Blockflöte</h2>
	<img src={Blockfloete} alt="" class="floating-wide" />
	<p>
		Die Blockflöte ist ein geeignetes Instrument für den Einstieg in die Musik. Da ihre technischen
		Ansprüche niedrig sind, bleibt der Freiraum, um die vielschichtige Welt der Musik
		kennenzulernen. Dabei werden Grunderfahrungen gesammelt, die später wertvoll für eine
		musikalische Weiterentwicklung sind.
	</p>
	<p>
		Seit vielen Jahren bemühen wir uns um ein angepasstes Unterrichtsangebot für Kinder in allen
		Altersstufen. Besonders im Grundschulalter ist eine musikalische Ausbildung ein geeignetes
		Mittel zur Persönlichkeitsentwicklung, ein Training für Aufmerksamkeit, Ausdauer und
		Intelligenz.
	</p>
	<p>
		Mittels Musik ist die Fähigkeit, einer Unterrichtsstunde in vollem Umfang folgen zu können, auf
		spielerische und interaktive Weise erlernbar. Das Verstehen der Notenschrift ist später eine
		wichtige Voraussetzung für das Musizieren, aber auch ein gutes Lesetraining.
	</p>
	<p>
		Genauso wollen wir Kindern die Freude am Musizieren vermitteln und Voraussetzungen für mentale
		Gesundheit stärken. Musik bietet Kindern eine Ausdrucksmöglichkeit für Emotionen, die sie verbal
		oft noch nicht artikulieren können. Kinder erleben direkt, dass sich Anstrengung auszahlt: Ein
		Stück, das zu Beginn schwer war, gelingt nach einigen Wochen des Übens. So fördert Musizieren
		das Selbstbewusstsein.
	</p>

	<h2>Klavier</h2>
	<img src={Klavier} alt="" class="floating" />
	<p>
		Das Klavier ist seit jeher ein beliebtes Instrument. Das liegt mit daran, dass das Klavier für
		alle Stilrichtungen geeignet ist und auch ein einzelner Spieler großes Klangvolumen erreichen
		kann.
	</p>
	<p>
		Das Erlernen benötigt jedoch nicht nur Ausdauer und Disziplin, sondern auch einen guten Lehrer,
		der von Anfang an die richtige Methode zeigt und auf Haltung und Technik achtet.
	</p>
	<p>
		Bei der Auswahl der Unterrichtsliteratur achte ich auf abwechslungsreiche Stücke aus der Klassik
		wie auch der moderneren Musik.
	</p>
	<p>Habe ich Ihr Interesse geweckt? Dann kommen Sie vorbei zu einer Schnupperstunde.</p>

	<h2>Saxophon</h2>
	<img src={Saxophon} alt="" class="floating-narrow" />
	<p>
		Das Saxophon ist ein Instrument, das es in allen Stimmlagen vom Sopranino bis zum
		Subkontrabass-Saxophon gibt. Klangreich und technisch vielseitig findet man es heute in
		zahlreichen progressiven Musikrichtungen und Stilen. Seine Verbreitung ist eng mit der
		Entwicklung des Jazz verbunden.
	</p>
	<p>
		Seine Zugehörigkeit zu der Familie der "Holzblasinstrumente" verdankt das Saxophon der
		Tonerzeugung durch ein einseitig geöffnetes Mundstück, kombiniert mit einem Rohrblatt (genauso
		wie bei der Klarinette). Von den mindestens acht Saxophonarten werden heute hauptsächlich
		Sopran-, Alt-, Tenor- und Bariton-Saxophon gespielt. Alle Arten Saxophone unterliegen der
		gleichen Griffweise und Notation.
	</p>
	<p>
		Das Saxophon ist ein modernes und gut konzeptioniertes Instrument, welches relativ leicht und
		schon frühzeitig erlernbar ist. Voraussetzungen sind das Vorhandensein der bleibenden vorderen
		Zähne und eine ausreichende körperliche Konstitution. Nach kurzer Unterrichtszeit ist es den
		meisten Saxophonschülern bereits möglich, in kleinen oder größeren Ensembles – in den Schulen
		wie auch im Rahmen unseres eigenen Angebotes – mitzuwirken.
	</p>
	<p>Der Spaß dabei ist garantiert ...</p>

	<h2>Violoncello</h2>
	<img src={Cello} alt="" class="floating-narrow" />
	<p>
		Das Cello ist ein erstaunlich vielseitiges Instrument. Dank seines vollen und warmen Klanges
		wird es immer mehr auch außerhalb der ernsten Musik geschätzt. Die Tonlage, die der menschlichen
		Stimme sehr ähnelt, ist vielleicht der entscheidende Grund, warum es in besonderer Weise Gemüt
		und Seele zu berühren vermag.
	</p>
	<p>
		Die gerade Sitzhaltung und die sehr natürlich anmutende "Umarmung" des Cellos beim Spielen sind
		unkompliziert und werden meist als körperfreundlich empfunden.
	</p>
	<p>
		Wer heute Cello spielt, hat mehr Möglichkeiten zum Ensemblespiel als viele andere
		Instrumentalisten. Da man sich ein Cello (auch leihweise) in verschiedenen Größen beschaffen
		kann, ist der Beginn des Unterrichts auf diesem Instrument nicht an ein bestimmtes Alter oder
		Größe des Musizierenden gebunden.
	</p>
	<p>
		Erfahrungsgemäß ist jedoch das persönliche Ausprobieren eines Instrumentes aussagekräftiger als
		alle theoretischen Informationen. Dabei bin ich gern behilflich - eine Probestunde ist
		unverbindlich.
	</p>

	<h2>Klarinette</h2>
	<img src={Klarinette} alt="" class="floating-wide" />
	<p>
		Die Klarinette erfreut sich seit ihrer Entstehungszeit einer ständig wachsender Beliebtheit.
		Dafür sorgen Ausdruckskraft, Charme und klangliche Variabilität, der große Tonumfang und die
		Möglichkeit virtuosen Spiels.
	</p>
	<p>
		Wolfgang Amadeus Mozart, aber auch der Jazzklarinettist Benny Goodman haben die Entwicklung der
		Klarinette stark geprägt. In allen musikalischen Stilen und Genres ist sie vertreten – es
		besteht ein riesiges Spektrum an Spielmöglichkeiten und Literatur.
	</p>
	<p>
		Für das Erlernen der Klarinette sollten Kinder entsprechende körperliche und musikalische
		Voraussetzungen erfüllen. Dies sind zum einen die bereits voll ausgebildeten bleibenden
		Schneidezähne sowie eine Handspanne, die das mühelose Greifen auf dem Instrument ermöglichen
		sollte. Die Anforderungen an Mundmuskulatur und bläserisches Vermögen sind deutlich größer als
		z.B. bei der Blockflöte. Es ist daher von großem Vorteil, zu Beginn einer Ausbildung bereits
		über ein musikalisches Grundwissen zu verfügen (Umgang mit Noten, Rhythmus, etc.).
	</p>
